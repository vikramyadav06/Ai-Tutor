#!/usr/bin/env python3
"""
Bundle the course content into course/bundle.js so index.html also works when opened
directly from disk (double-click), where browsers block fetch() of local files.

    python tools/build_bundle.py

Run it after editing any lesson.json, exercise or solution. The GitHub Pages site does not
need it (it fetches the files directly), but keeping it fresh costs nothing.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COURSE = ROOT / "course"


def main():
    catalog = json.loads((COURSE / "catalog.json").read_text(encoding="utf-8"))
    lessons, files = {}, {}
    for m in catalog["modules"]:
        folder = ROOT / m["folder"]
        lesson = folder / "lesson.json"
        if not lesson.exists():
            continue
        lessons[m["id"]] = json.loads(lesson.read_text(encoding="utf-8"))
        for sub in ("exercises", "solutions"):
            for f in sorted((folder / sub).glob("*.py")):
                files[f.relative_to(ROOT).as_posix()] = f.read_text(encoding="utf-8")
    bundle = {"catalog": catalog, "lessons": lessons, "files": files}
    out = COURSE / "bundle.js"
    out.write_text(
        "// Generated by tools/build_bundle.py. Do not edit by hand.\n"
        "window.COURSE_BUNDLE = " + json.dumps(bundle, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(f"Bundled {len(lessons)} lessons and {len(files)} code files into {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
